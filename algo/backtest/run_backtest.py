# Conservative, standard per-side transaction-cost haircut applied to every fill (2026-08-25,
# closing the "zero slippage/spread on every fill" gap documented in run_backtest()'s docstring).
# 5 bps/side is a common, well-precedented default for liquid US large/mid-cap equities in
# practitioner and academic backtesting when real broker-level slippage data isn't available -
# NOT derived from this system's own execution history (algo_tca has 0 local rows to calibrate
# against, see the docstring below). This exists to avoid the opposite, worse error - reporting
# backtest performance as if every fill were free - not to claim precision this system doesn't
# have. Replace with a real distribution drawn from `algo_tca.slippage_bps` once that table has
# live rows; until then this is an explicit, visible estimate, not silent zero-cost execution.
DEFAULT_SLIPPAGE_BPS = 5.0


def _fetch_risk_free_rate_annual() -> float:
    """Real 3-month T-bill rate (FRED DGS3MO), decimal annual - same source/convention as
    algo/reporting/performance.py's rolling_sharpe(). Added 2026-08-25 (goal: closing the
    "run_backtest.py duplicates the pre-fix raw-return Sharpe formula" gap found auditing
    the just-fixed calculate_sharpe_ratio() risk-free-rate bug - this script independently
    reimplemented the same formula inline instead of calling MetricsCalculator, so it carried
    the identical rf=0 assumption. Falls back to 0.0 (old behavior) if DGS3MO is unavailable,
    same non-fatal-degradation choice as rolling_sharpe().
    """
    try:
        with DatabaseContext("read") as cur:
            cur.execute(
                "SELECT value::float FROM economic_data WHERE series_id = 'DGS3MO' "
                "AND date <= CURRENT_DATE AND value IS NOT NULL ORDER BY date DESC LIMIT 1"
            )
            row = cur.fetchone()
            if row is not None and row[0] is not None:
                return float(row[0]) / 100.0
    except (psycopg2.DatabaseError, psycopg2.OperationalError) as e:
        logger.warning(f"[BACKTEST] DGS3MO risk-free rate lookup failed ({e}) - using 0.0")
    else:
        logger.warning("[BACKTEST] DGS3MO risk-free rate unavailable - using 0.0")
    return 0.0


def _get_trading_dates(start: date, end: date) -> list[date]:
    try:
        with DatabaseContext("read") as cur:
            cur.execute(
                """
                SELECT DISTINCT date FROM price_daily
                WHERE date >= %s AND date <= %s
                ORDER BY date ASC
                """,
                (start, end),
            )
            return [row[0] for row in cur.fetchall()]
    except (psycopg2.DatabaseError, psycopg2.OperationalError) as e:
        raise RuntimeError(f"[BACKTEST] FATAL: Cannot fetch trading dates from price_daily: {e}") from e


def _get_daily_buy_signals(
    signal_date: date, min_composite: float, rank_by: str = "signal_quality_score"
) -> list[dict[str, Any]]:
    """Get BUY signals detected on signal_date, ranked by `rank_by`.

    rank_by="signal_quality_score" (default, unchanged behavior): ranks by
    signal_quality_score (contemporaneous - no look-ahead bias). composite_score is also
    fetched from `stock_scores` for informational use only, NOT filtered/ranked by it, since
    that table has no date dimension (always TODAY's value, would be look-ahead bias against
    a historical signal_date). min_composite is accepted for API compatibility but unused in
    this mode.

    rank_by="composite_score_pit" (added 2026-09-04, real-money-readiness review, closing the
    gap this module's docstring flagged since 2026-08-26): ranks by composite_score sourced
    from `stock_scores_history` (migration 1221), joined point-in-time - the most recent
    `score_date <= signal_date` per symbol, mirroring the asof-join pattern already used by
    `algo/risk/market_exposure.py`'s `read_market_regime()`. This is genuinely contemporaneous
    (never a future score) and lets this backtest actually test live Phase 7's real ranking
    mechanism (composite_score-primary since 2026-08-27) without reintroducing look-ahead bias.
    min_composite IS applied as a real filter in this mode (rows with no score on-or-before
    signal_date, or below the threshold, are excluded) - unlike the default mode, since a
    genuinely point-in-time composite_score makes that threshold meaningful here.
    CAVEAT: as of 2026-09-04, stock_scores_history only has snapshots from 2026-08-24 onward
    (~11 distinct dates) - a backtest run in this mode over that short a window is not
    statistically meaningful yet (same underlying data-shallowness documented in
    tests/unit/test_regime_adaptive_exits_backtest_infeasible_20260825.py for a different
    table). The wiring is correct and ready for when the table has real depth; don't treat an
    early run's Sharpe/win-rate as evidence either way until it does.

    NOTE: the "entry_price" field returned here (signal_date's own close) is INFORMATIONAL
    ONLY as of 2026-08-27 - run_backtest()'s main loop no longer uses it directly for sizing/
    cost basis. It fetches signals one trading day BEHIND its current sim_date and re-resolves
    the actual fill price via a fresh _get_prices_batch() call on sim_date itself, to model the
    real one-day (modal) lag between signal detection and live Phase 8 execution. See the
    module docstring's "Entry fill assumption" note.
    """
    if rank_by not in ("signal_quality_score", "composite_score_pit"):
        raise ValueError(
            f"[BACKTEST] Invalid rank_by={rank_by!r}. Must be 'signal_quality_score' or 'composite_score_pit'."
        )
    try:
        with DatabaseContext("read") as cur:
            if rank_by == "composite_score_pit":
                cur.execute(
                    """
                    SELECT b.symbol, b.close, b.high, b.low, b.sma_50, b.strength,
                           b.buylevel, b.stoplevel,
                           b.signal_quality_score, b.entry_quality_score,
                           s.composite_score, s.rs_percentile
                    FROM buy_sell_daily b
                    LEFT JOIN LATERAL (
                        SELECT composite_score, rs_percentile
                        FROM stock_scores_history sh
                        WHERE sh.symbol = b.symbol AND sh.score_date <= %s
                        ORDER BY sh.score_date DESC
                        LIMIT 1
                    ) s ON TRUE
                    WHERE b.date = %s
                      AND b.signal_type = 'BUY'
                      AND b.close IS NOT NULL
                      AND b.sma_50 IS NOT NULL
                      AND b.close > b.sma_50
                      AND b.signal_quality_score IS NOT NULL
                      AND s.composite_score IS NOT NULL
                      AND s.composite_score >= %s
                    ORDER BY s.composite_score DESC
                    """,
                    (signal_date, signal_date, min_composite),
                )
            else:
                cur.execute(
                    """
                    SELECT b.symbol, b.close, b.high, b.low, b.sma_50, b.strength,
                           b.buylevel, b.stoplevel,
                           b.signal_quality_score, b.entry_quality_score,
                           s.composite_score, s.rs_percentile
                    FROM buy_sell_daily b
                    LEFT JOIN stock_scores s ON s.symbol = b.symbol
                    WHERE b.date = %s
                      AND b.signal_type = 'BUY'
                      AND b.close IS NOT NULL
                      AND b.sma_50 IS NOT NULL
                      AND b.close > b.sma_50
                      AND b.signal_quality_score IS NOT NULL
                    ORDER BY b.signal_quality_score DESC
                    """,
                    (signal_date,),
                )
            rows = cur.fetchall()

        signals = []
        skipped_count = 0
        for r in rows:
            close = float(r[1])
            if not close:
                logger.warning(
                    f"[BACKTEST] Skipping {r[0]} on {signal_date}: close price is {close} "
                    f"(falsy value detected during signal processing)"
                )
                skipped_count += 1
                continue
            if r[5] is None:
                raise ValueError(
                    f"Signal strength missing for {r[0]} on {signal_date} - "
                    f"cannot rank signal quality without strength data"
                )
            signals.append(
                {
                    "symbol": r[0],
                    "entry_price": close,
                    "high": float(r[2]) if r[2] is not None else None,
                    "low": float(r[3]) if r[3] is not None else None,
                    "sma_50": float(r[4]) if r[4] is not None else None,
                    "signal_strength": float(r[5]),
                    "buylevel": float(r[6]) if r[6] is not None else None,
                    "stoplevel": float(r[7]) if r[7] is not None else None,
                    "signal_quality_score": float(r[8]),
                    "entry_quality_score": float(r[9]) if r[9] is not None else None,
                    "composite_score": float(r[10]) if r[10] is not None else None,
                    "rs_percentile": float(r[11]) if r[11] is not None else None,
                }
            )

        return signals
    except (ValueError, ZeroDivisionError, TypeError) as e:
        raise RuntimeError(f"[BACKTEST] FATAL: Cannot fetch buy signals for {signal_date}: {e}") from e


