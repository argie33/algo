#!/usr/bin/env python3
"""
Backtest: Composite Score + Buy/Sell Signals Strategy

Simulates the live algo strategy historically:
  - Entry trigger: BUY signal in buy_sell_daily (pivot breakout above swing high with SMA50 filter)
  - Ranking: signal_quality_score (contemporaneous, from buy_sell_daily) - this INTENTIONALLY
    NO LONGER matches live Phase 7's ranking as of 2026-08-27 (see below for why).
  - Entry fill assumption: FIXED 2026-08-27 (real-money-readiness review) - entries now fill at
    the NEXT trading day's close after the signal fired, not the signal day's own close. Live-DB
    evidence (n=104 closed local trades) showed real Phase 8 entries land anywhere from the SAME
    calendar day (50/116) to 1 day later (62/116, the modal case) to 3 days later (4/116)
    relative to signal_date - never simulated at all under the old same-day-close assumption.
    This backtest now uses the single MODAL case (1 trading day of lag) as a materially more
    realistic default than zero lag; it is still an approximation (a full lag-distribution model
    would need real fill-timestamp data this local environment doesn't have) but a
    directionally-correct one, since a working breakout keeps running while the real pipeline
    catches up to it, so any positive lag pushes entries worse on average, not better. Of the 36
    live trades matchable back to their triggering buy_sell_daily.buylevel, entries averaged
    +0.75% (median +0.55%) ABOVE that breakout trigger price, worse than the trigger level on
    72% of them - the flat DEFAULT_SLIPPAGE_BPS haircut alone did not capture this; the lag
    itself needed to be simulated, not just a bigger flat haircut. See `run_backtest()`'s own
    docstring for the exact mechanism (`prev_signal_date`/`fill_prices`).

Live Phase 7 ranking history: originally composite_score, Session 377 switched it to
signal_quality_score (SQS) on a short-term-predictive-power hypothesis, a 2026-08-26 empirical
check of live signals found the opposite (near-zero/inverse correlation with forward returns -
see signal_quality_score_pooled_check_no_predictive_power_found_20260825 in memory), and live
Phase 7 was switched BACK to composite_score-primary ranking 2026-08-27 (real-money-readiness
review; see phase7_signal_generation.py's module docstring for the full history/evidence).

This backtest script's DEFAULT ranking (signal_quality_score) deliberately was NOT switched to
match live Phase 7 when the "the mechanism differs" gap was first found - it can't be, without
introducing worse look-ahead bias than the SQS-vs-composite_score question it would be trying
to answer. `stock_scores` has no historical date dimension (current snapshot only) -
composite_score sourced from it is always TODAY's value regardless of the historical
signal_date being simulated, so ranking backtest history by IT SPECIFICALLY would use future
information a live run on that historical date never had. signal_quality_score IS
contemporaneous (stored per-date on buy_sell_daily), which is why it remained this script's
DEFAULT ranking key even after live Phase 7 stopped using it that way.
2026-08-26: signal_quality_score itself has since been empirically checked against real live
outcomes and found to show no robust predictive power (see
signal_quality_score_pooled_check_no_predictive_power_found_20260825 in memory / a
pooled correlation ~0, non-monotonic quintiles) - meaning this backtest's DEFAULT-mode
historical Sharpe numbers are generated by ranking on a score shown not to work live, so they
should NOT be treated as confirmation that live Phase 7's CURRENT (composite_score-based)
ranking works either.

FIXED 2026-09-04 (real-money-readiness review, financial-calculation-integrity audit): the gap
above is now closed at the code level. `stock_scores_history` (migration 1221, point-in-time
composite_score by symbol+date) exists specifically for this - pass `--rank-by
composite_score_pit` (or `rank_by="composite_score_pit"` to `run_backtest()`) to rank same-day
BUY signals by a genuinely point-in-time composite_score, asof-joined by (symbol,
score_date<=signal_date) in `_get_daily_buy_signals()`, rather than `stock_scores`'s always-
current snapshot. This actually tests live Phase 7's real ranking mechanism
(composite_score-primary since 2026-08-27) without look-ahead bias. CAVEAT, still real: as of
2026-09-04 `stock_scores_history` only has snapshots from 2026-08-24 onward (~11 distinct
dates) - a run in this mode today is not yet statistically meaningful, same underlying
data-shallowness this repo's 2026-08-25 regime-adaptive-exits finding hit for a different
table (see tests/unit/test_regime_adaptive_exits_backtest_infeasible_20260825.py). The wiring
is correct and ready; don't treat an early `composite_score_pit` run's Sharpe/win-rate as
real evidence until the table has genuine depth (a year+ of daily snapshots, ideally spanning
more than one regime). The default ranking stays `signal_quality_score` until then, so existing
callers/results are unaffected by this change. Momentum sub-score is price-based (1m/3m/6m/12m)
so recency bias is expected for stocks that gained since signal date, in either ranking mode.

Usage:
    python -m algo.backtest.run_backtest [options]

    --start-date DATE    Start date for backtest (default: 2 years ago)
    --end-date DATE      End date (default: today)
    --initial-capital N  Starting capital in dollars (default: 100000)
    --max-positions N    Max concurrent positions (default: 10)
    --min-composite N    Min composite_score to qualify (default: 50)
    --profit-target PCT  Profit target % (default: 20)
    --stop-loss PCT      Stop loss % (default: 8)
    --max-hold-days N    Max holding period in days (default: 60)
    --position-size PCT  Fixed position size as % of portfolio (default: 10)
    --strategy NAME      Strategy name for results table (default: composite_score_signals)
    --slippage-bps BPS   Per-side slippage/spread haircut in basis points (default: 5.0)
    --dry-run            Print results without writing to DB
"""

