"""Structural-typing protocol shared by Orchestrator's mixin files (file-size ratchet split,
2026-09-10). Declares every attribute/method any mixin references on `self` that isn't
defined in that same mixin, so mypy can type-check each mixin's `self.` usage without each
file repeating its own TYPE_CHECKING stub block - see algo/orchestration/orchestrator.py for
the concrete Orchestrator class these mixins compose into (it, not this Protocol, is what
actually runs). Used only under `if TYPE_CHECKING`; has zero runtime effect.
"""

from __future__ import annotations

from typing import Any, Protocol

from algo.orchestrator.phase_executor import OrchestratorPhaseExecutor


