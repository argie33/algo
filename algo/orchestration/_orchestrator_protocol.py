    alerts: Any
    config: Any
    db_monitor: Any
    degraded_mode: bool
    dry_run: bool
    execution_mode: str
    execution_tracker: Any
    executor: OrchestratorPhaseExecutor
    halt_manager: Any
    lock_manager: Any
    phase_results: Any
    run_date: Any
    run_id: str
    run_start: float
    verbose: bool

    def _acquire_run_lock(self, *args: Any, **kwargs: Any) -> Any: ...
    def _check_loader_health(self, *args: Any, **kwargs: Any) -> Any: ...
    def _cleanup_expired_locks(self, *args: Any, **kwargs: Any) -> Any: ...
    def _cleanup_stale_loader_locks(self, *args: Any, **kwargs: Any) -> Any: ...
    def _cleanup_stale_orchestrator_run_locks(self, *args: Any, **kwargs: Any) -> Any: ...
    def _emit_performance_metrics(self, *args: Any, **kwargs: Any) -> Any: ...
    def _execute_phases(self, *args: Any, **kwargs: Any) -> dict[str, Any]: ...
    def _executor_phase_1(self, *args: Any, **kwargs: Any) -> Any: ...
    def _executor_phase_2(self, *args: Any, **kwargs: Any) -> Any: ...
    def _executor_phase_3(self, *args: Any, **kwargs: Any) -> Any: ...
    def _executor_phase_4(self, *args: Any, **kwargs: Any) -> Any: ...
    def _executor_phase_5(self, *args: Any, **kwargs: Any) -> Any: ...
    def _executor_phase_6(self, *args: Any, **kwargs: Any) -> Any: ...
    def _executor_phase_7(self, *args: Any, **kwargs: Any) -> Any: ...
    def _executor_phase_8(self, *args: Any, **kwargs: Any) -> Any: ...
    def _executor_phase_9(self, *args: Any, **kwargs: Any) -> Any: ...
    def _final_report(self, *args: Any, **kwargs: Any) -> dict[str, Any]: ...
    def _handle_concurrency_lock(self, *args: Any, **kwargs: Any) -> dict[str, Any] | None: ...
    def _handle_executor_result(self, *args: Any, **kwargs: Any) -> dict[str, Any] | None: ...
    def _install_shutdown_handler(self, *args: Any, **kwargs: Any) -> Any: ...
    def _kill_long_running_loaders(self, *args: Any, **kwargs: Any) -> Any: ...
    def _release_run_lock(self, *args: Any, **kwargs: Any) -> Any: ...
    def _resolve_execution_mode(self, *args: Any, **kwargs: Any) -> Any: ...
    def _restore_shutdown_handler(self, *args: Any, **kwargs: Any) -> Any: ...
    def _run_pipeline_health_sweep(self, *args: Any, **kwargs: Any) -> Any: ...
    def _run_preflight_checks(self, *args: Any, **kwargs: Any) -> dict[str, Any] | None: ...
    def _save_early_exit_log(self, *args: Any, **kwargs: Any) -> Any: ...
    def _save_orchestrator_run_status(self, *args: Any, **kwargs: Any) -> Any: ...
    def _setup_executor(self, *args: Any, **kwargs: Any) -> OrchestratorPhaseExecutor: ...
    def _validate_required_tables(self, *args: Any, **kwargs: Any) -> Any: ...
    def _validate_startup_configuration(self, *args: Any, **kwargs: Any) -> Any: ...
    def _verify_alpaca_account_type(self, *args: Any, **kwargs: Any) -> Any: ...
